// Deploys the landing page to the local nginx container that the Cloudflare Tunnel serves as git-pro.longtd.me.
// Usage: node scripts/deploy-site.cjs           build site-dist/, generate the CSP, rebuild and restart the container, verify
//        node scripts/deploy-site.cjs --verify  only verify the running container
// The container listens on 127.0.0.1:${GIT_PRO_SITE_PORT:-4280}. Prints a JSON summary and exits 1 on any failure.
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const dist = path.join(root, 'site-dist');
const compose = path.join(root, 'site', 'deploy', 'compose.yml');
const generated = path.join(root, 'site', 'deploy', '.generated');
const port = Number(process.env.GIT_PRO_SITE_PORT || 4280);
const verifyOnly = process.argv.includes('--verify');

function run(command, args) {
  const result = spawnSync(command, args, { cwd: root, stdio: 'inherit', windowsHide: true, shell: false });
  if (result.error) throw new Error(`${command} could not start: ${result.error.message}`);
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} exited ${result.status}`);
}

// Hashes every executable inline <script> and every style attribute, so the CSP needs no 'unsafe-inline'.
function contentSecurityPolicy() {
  const scripts = new Set(), styles = new Set();
  const hash = text => `'sha256-${crypto.createHash('sha256').update(text, 'utf8').digest('base64')}'`;
  const pages = [];
  const collect = directory => { for (const entry of fs.readdirSync(directory, { withFileTypes: true })) { const full = path.join(directory, entry.name); if (entry.isDirectory()) collect(full); else if (entry.name.endsWith('.html')) pages.push(full); } };
  collect(dist);
  for (const page of pages) {
    const html = fs.readFileSync(page, 'utf8');
    for (const match of html.matchAll(/<script(\s[^>]*)?>([\s\S]*?)<\/script>/g)) {
      const attributes = match[1] || '';
      if (/\ssrc=/.test(attributes) || /type="application\/ld\+json"/.test(attributes)) continue;
      scripts.add(hash(match[2]));
    }
    for (const match of html.matchAll(/\sstyle="([^"]*)"/g)) styles.add(hash(match[1]));
  }
  const styleSources = ["'self'", ...(styles.size ? ["'unsafe-hashes'", ...styles] : [])];
  return [
    "default-src 'none'", `script-src 'self' ${[...scripts].join(' ')}`.trim(), `style-src ${styleSources.join(' ')}`,
    // styles.css draws small icons (the external-link arrow) as data: SVG masks.
    "img-src 'self' data:", "font-src 'self'", "manifest-src 'self'", "connect-src 'self'",
    "base-uri 'none'", "form-action 'none'", "frame-ancestors 'none'", 'upgrade-insecure-requests',
  ].join('; ');
}

function writeHeaders() {
  const csp = contentSecurityPolicy();
  if (csp.includes('"')) throw new Error('Generated CSP contains a double quote.');
  const lines = [
    `add_header Content-Security-Policy "${csp}" always;`,
    'add_header X-Content-Type-Options "nosniff" always;',
    'add_header Referrer-Policy "strict-origin-when-cross-origin" always;',
    'add_header Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=()" always;',
    'add_header X-Frame-Options "DENY" always;',
    'add_header Cross-Origin-Opener-Policy "same-origin" always;',
    // No includeSubDomains or preload: other longtd.me hosts keep their own policy.
    'add_header Strict-Transport-Security "max-age=15552000" always;',
  ];
  fs.mkdirSync(generated, { recursive: true });
  fs.writeFileSync(path.join(generated, 'security-headers.conf'), `# Generated by scripts/deploy-site.cjs; do not edit.\n${lines.join('\n')}\n`);
  return csp;
}

function request(pathname, headers = {}) {
  return new Promise(resolve => {
    const req = http.get({ host: '127.0.0.1', port, path: pathname, headers, timeout: 5000 }, response => {
      const chunks = [];
      response.on('data', chunk => chunks.push(chunk));
      response.on('end', () => resolve({ status: response.statusCode, headers: response.headers, body: Buffer.concat(chunks) }));
    });
    req.on('timeout', () => req.destroy(new Error('timeout')));
    req.on('error', error => resolve({ status: 0, error: error.message, headers: {}, body: Buffer.alloc(0) }));
  });
}

async function verify() {
  const deadline = Date.now() + 30_000;
  let home = await request('/');
  while (home.status !== 200 && Date.now() < deadline) { await new Promise(resolve => setTimeout(resolve, 1000)); home = await request('/'); }
  const checks = [];
  const check = (name, passed, detail) => checks.push({ name, passed: Boolean(passed), ...(passed ? {} : { detail }) });
  check('home 200 html', home.status === 200 && /^text\/html/.test(home.headers['content-type'] || ''), `${home.status} ${home.headers['content-type'] || home.error || ''}`);
  check('home matches site-dist', fs.existsSync(path.join(dist, 'index.html')) && home.body.equals(fs.readFileSync(path.join(dist, 'index.html'))), 'served index.html differs from site-dist/index.html');
  for (const header of ['content-security-policy', 'x-content-type-options', 'referrer-policy', 'x-frame-options']) check(`header ${header}`, home.headers[header], 'missing');
  check('no server version', !/\d/.test(home.headers.server || ''), home.headers.server);
  const assets = { '/styles.css': /^text\/css/, '/main.js': /javascript/, '/og.jpg': /^image\/jpeg/, '/favicon.svg': /^image\/svg\+xml/, '/images/history.jpg': /^image\/jpeg/, '/site.webmanifest': /^application\/manifest\+json/, '/robots.txt': /^text\/plain/, '/sitemap.xml': /xml/ };
  for (const [asset, type] of Object.entries(assets)) {
    const response = await request(asset);
    check(`asset ${asset}`, response.status === 200 && type.test(response.headers['content-type'] || '') && response.headers['content-security-policy'], `${response.status} ${response.headers['content-type'] || ''}`);
  }
  const missing = await request('/does-not-exist');
  check('missing path 404 page', missing.status === 404 && missing.body.toString('utf8').includes('<h1'), `${missing.status}`);
  const hidden = await request('/.generated/security-headers.conf');
  check('dot paths hidden', hidden.status === 404, `${hidden.status}`);
  const deployFiles = await request('/deploy/nginx.conf');
  check('deploy files not served', deployFiles.status === 404, `${deployFiles.status}`);
  // What Cloudflare sends for a plain-HTTP visitor: a permanent redirect to the same path over HTTPS.
  const plain = await request('/faq?x=1', { host: 'git-pro.longtd.me', 'x-forwarded-proto': 'http' });
  check('http visitors redirect to https', plain.status === 301 && plain.headers.location === 'https://git-pro.longtd.me/faq?x=1', `${plain.status} ${plain.headers.location || ''}`);
  const secure = await request('/', { host: 'git-pro.longtd.me', 'x-forwarded-proto': 'https' });
  check('https visitors served', secure.status === 200, `${secure.status}`);
  return checks;
}

(async () => {
  const summary = { url: `http://127.0.0.1:${port}/`, publicUrl: 'https://git-pro.longtd.me/' };
  if (!verifyOnly) {
    run(process.execPath, [path.join('scripts', 'build-site.cjs')]);
    summary.csp = writeHeaders();
    run('docker', ['compose', '-f', compose, 'up', '-d', '--build', '--remove-orphans']);
  }
  const checks = await verify();
  summary.passed = checks.every(item => item.passed);
  summary.failed = checks.filter(item => !item.passed);
  summary.checks = checks.length;
  console.log(JSON.stringify(summary, null, 2));
  if (!summary.passed) process.exitCode = 1;
})().catch(error => { console.error(error.message); process.exitCode = 1; });
